#!/usr/bin/env bash
#
# Keeps the tool-specific copies in step with their sources:
#
#   .agents/skills/     -> .claude/skills/         (Codex-only <skill>/agents/ is skipped)
#   .claude/agents/*.md -> .codex/agents/*.toml    (description and instructions)
#
# Usage:
#   .agents/sync.sh          write the copies
#   .agents/sync.sh --check  change nothing; exit 1 when a copy is out of date (CI)
#
# In a Codex agent file everything above `developer_instructions` except the
# `description` line is Codex-only (model_reasoning_effort, sandbox_mode, …)
# and is kept as it is.
#
# A project that does not use one of the tools has no `.claude/` or `.codex/`
# folder; the matching step is skipped.

set -euo pipefail

cd "$(dirname "$0")/.."

check=0
if [[ "${1:-}" == "--check" ]]; then
  check=1
elif [[ $# -gt 0 ]]; then
  echo "Usage: .agents/sync.sh [--check]" >&2
  exit 2
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
status=0

# Prints the value of a frontmatter key of a Claude agent file, unquoted.
frontmatter() {
  awk -v key="$2" '
    /^---$/ { n++; next }
    n == 1 && index($0, key ": ") == 1 {
      value = substr($0, length(key) + 3)
      if (value ~ /^".*"$/) { value = substr(value, 2, length(value) - 2) }
      print value
      exit
    }
  ' "$1"
}

# Prints the body of a Claude agent file (everything after the frontmatter).
body() {
  awk 'n >= 2 { print } /^---$/ { n++ }' "$1" | sed '/./,$!d'
}

# Prints the Codex agent file generated from a Claude agent file.
codex_agent() {
  local md="$1" toml="$2" name description
  name="$(basename "$md" .md)"
  description="$(frontmatter "$md" description | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"

  if [[ -f "$toml" ]]; then
    awk -v description="$description" '
      /^developer_instructions = / { exit }
      /^description = / { print "description = \"" description "\""; next }
      { print }
    ' "$toml"
  else
    echo "# Codex counterpart of .claude/agents/$name.md — generated by .agents/sync.sh."
    echo "name = \"$name\""
    echo "description = \"$description\""
  fi
  echo "developer_instructions = '''"
  body "$md"
  echo "'''"
}

# Prints the verdict of a --check run and exits with the collected status.
finish() {
  if [[ $check -eq 1 && $status -eq 0 ]]; then
    echo "In sync."
  elif [[ $check -eq 1 ]]; then
    echo "Run .agents/sync.sh and commit the result." >&2
  fi
  exit $status
}

# --- Skills ------------------------------------------------------------------

if [[ ! -d .claude ]]; then
  echo "Skipped skills: no .claude/ folder."
elif [[ $check -eq 1 ]]; then
  mkdir "$tmp/skills"
  rsync -a --exclude='/*/agents/' .agents/skills/ "$tmp/skills/"
  if ! diff -r "$tmp/skills" .claude/skills > "$tmp/skills.diff" 2>&1; then
    echo "Out of date: .claude/skills/ differs from .agents/skills/" >&2
    sed -n -e "s#$tmp/skills#.agents/skills#g" -e '1,20p' "$tmp/skills.diff" >&2
    status=1
  fi
else
  rsync -a --delete --delete-excluded --exclude='/*/agents/' .agents/skills/ .claude/skills/
  echo "Synced .agents/skills/ -> .claude/skills/"
fi

# --- Subagents ---------------------------------------------------------------

if [[ ! -d .claude/agents || ! -d .codex/agents ]]; then
  echo "Skipped subagents: .claude/agents/ and .codex/agents/ are not both present."
  finish
fi

for md in .claude/agents/*.md; do
  name="$(basename "$md" .md)"
  toml=".codex/agents/$name.toml"
  codex_agent "$md" "$toml" > "$tmp/$name.toml"

  if grep -q "'''" <(body "$md"); then
    echo "Error: $md contains ''' and cannot be written as a TOML literal string." >&2
    status=1
    continue
  fi

  if [[ -f "$toml" ]] && cmp -s "$tmp/$name.toml" "$toml"; then
    continue
  fi
  if [[ $check -eq 1 ]]; then
    echo "Out of date: $toml differs from $md" >&2
    status=1
  else
    cp "$tmp/$name.toml" "$toml"
    echo "Wrote $toml"
  fi
done

for toml in .codex/agents/*.toml; do
  if [[ ! -f ".claude/agents/$(basename "$toml" .toml).md" ]]; then
    echo "Orphan: $toml has no .claude/agents counterpart" >&2
    status=1
  fi
done

finish
